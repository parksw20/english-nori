function block(emoji: string, title: string, lines: (string | Node)[]): HTMLElement {
  return el('div', { class: 'en-man-card' }, [
    el('div', { class: 'en-man-head', text: `${emoji} ${title}` }),
    el(
      'ul',
      { class: 'en-man-list' },
      lines.map((l) => el('li', typeof l === 'string' ? { text: l } : {}, typeof l === 'string' ? [] : [l]))
    ),
  ])
}

